/* STRINGS.md, generated from the built page.
 *
 * WHY IT IS GENERATED. A hand-written string inventory is out of date the
 * first time somebody edits a sentence, and an inventory that is wrong is
 * worse than none: it sends whoever is reading it to change copy that no
 * longer exists. This renders the real page, walks every view in document
 * order, and writes down what is actually there.
 *
 *   node tools/strings.mjs           write STRINGS.md
 *   node tools/strings.mjs --check   fail if STRINGS.md is out of date
 *
 * The check runs in `npm run verify`, so the file cannot drift from the
 * product without the build going red.
 *
 * WHAT IT CANNOT SEE, and how that is handled. A DOM walk finds anything
 * rendered, including the states that are in the markup but hidden. It
 * cannot find a string that only exists inside a function: toasts, network
 * error messages and validation text. Those are read out of the source
 * instead, so the two halves together cover everything anybody reads.
 */
